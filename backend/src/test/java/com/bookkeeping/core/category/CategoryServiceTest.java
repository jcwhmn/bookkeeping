    @Nested
    @DisplayName("reorderCategories")
    class ReorderCategories {

        @Test
        @DisplayName("assigns sequential sortOrder starting at 0")
        void assigns_sequential_sortOrder() {
            Category c1 = testCategory.toBuilder().sortOrder(0).build();
            Category c2 = testCategory.toBuilder().sortOrder(1).build();
            Category c3 = testCategory.toBuilder().sortOrder(2).build();

            when(securityUtils.requireCurrentUser()).thenReturn(testUser);
            when(categoryRepository.findByIdAndUserId(10L, 1L)).thenReturn(Optional.of(c1));
            when(categoryRepository.findByIdAndUserId(20L, 1L)).thenReturn(Optional.of(c2));
            when(categoryRepository.findByIdAndUserId(30L, 1L)).thenReturn(Optional.of(c3));
            when(categoryRepository.save(any(Category.class))).thenAnswer(inv -> inv.getArgument(0));

            categoryService.reorderCategories(List.of(10L, 20L, 30L));

            ArgumentCaptor<Category> captor = ArgumentCaptor.forClass(Category.class);
            verify(categoryRepository, times(3)).save(captor.capture());
            List<Category> savedCategories = captor.getAllValues();
            assertEquals(0, savedCategories.get(0).getSortOrder());
            assertEquals(1, savedCategories.get(1).getSortOrder());
            assertEquals(2, savedCategories.get(2).getSortOrder());
        }

        @Test
        @DisplayName("does nothing when category list is empty")
        void does_nothing_when_empty() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);

            categoryService.reorderCategories(List.of());

            verify(categoryRepository, never()).findByIdAndUserId(anyLong(), anyLong());
            verify(categoryRepository, never()).save(any());
        }

        @Test
        @DisplayName("throws CATEGORY_NOT_FOUND when a category is not owned by user")
        void throws_when_category_not_owned() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);
            when(categoryRepository.findByIdAndUserId(10L, 1L)).thenReturn(Optional.of(testCategory));
            when(categoryRepository.findByIdAndUserId(999L, 1L)).thenReturn(Optional.empty());

            BusinessException ex = assertThrows(BusinessException.class,
                    () -> categoryService.reorderCategories(List.of(10L, 999L)));
            assertEquals(ResultCode.CATEGORY_NOT_FOUND.getCode(), ex.getErrorCode());
        }
    }

