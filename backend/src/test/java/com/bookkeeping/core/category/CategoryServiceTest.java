        void creates_multiple() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);
            when(categoryRepository.save(any(Category.class))).thenAnswer(inv -> inv.getArgument(0));

            List<CategoryService.BatchCreateItem> items = List.of(
                    new CategoryService.BatchCreateItem("Salary", CategoryType.INCOME, null, "mdi-cash", "#4CAF50", null),
                    new CategoryService.BatchCreateItem("Food", CategoryType.EXPENSE, null, "mdi-food", "#FF5722", "Eating out"),
                    new CategoryService.BatchCreateItem("Transfer", CategoryType.TRANSFER, null, null, null, null)
            );

            List<CategoryDto> result = categoryService.batchCreate(items);

            assertEquals(3, result.size());
            verify(categoryRepository, times(3)).save(any(Category.class));
        }

        @Test
        @DisplayName("returns empty list when items is empty")
        void empty_items() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);

            List<CategoryDto> result = categoryService.batchCreate(List.of());

            assertTrue(result.isEmpty());
            verify(categoryRepository, never()).save(any());
        }

        @Test
        @DisplayName("throws CATEGORY_TYPE_INVALID when any item has null type")
        void throws_when_type_null() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);
            when(categoryRepository.save(any(Category.class))).thenAnswer(inv -> inv.getArgument(0));

            List<CategoryService.BatchCreateItem> items = List.of(
                    new CategoryService.BatchCreateItem("Good", CategoryType.INCOME, null, null, null, null),
                    new CategoryService.BatchCreateItem("Bad", null, null, null, null, null)
            );

            BusinessException ex = assertThrows(BusinessException.class,
                    () -> categoryService.batchCreate(items));
            assertEquals(ResultCode.CATEGORY_TYPE_INVALID.getCode(), ex.getErrorCode());
            // The first valid item was saved before the second invalid item caused the exception
            verify(categoryRepository, times(1)).save(any(Category.class));
        }

        @Test
        @DisplayName("throws CATEGORY_TYPE_INVALID when first item has null type")
        void throws_when_first_item_type_null() {
            when(securityUtils.requireCurrentUser()).thenReturn(testUser);

            List<CategoryService.BatchCreateItem> items = List.of(
                    new CategoryService.BatchCreateItem("Bad", null, null, null, null, null)
            );

            BusinessException ex = assertThrows(BusinessException.class,
                    () -> categoryService.batchCreate(items));
            assertEquals(ResultCode.CATEGORY_TYPE_INVALID.getCode(), ex.getErrorCode());
            verify(categoryRepository, never()).save(any());
        }
